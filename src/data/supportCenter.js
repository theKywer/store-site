export function filterHelpQuestions(query = '', categoryId = 'all') {
  const normalizedQuery = query.trim().toLocaleLowerCase('ru-RU')

  return helpQuestions.filter((item) => {
    const matchesCategory = categoryId === 'all' || item.category === categoryId
    const haystack = `${item.question} ${item.answer} ${item.keywords} ${
      helpCategories.find((category) => category.id === item.category)?.title || ''
    }`.toLocaleLowerCase('ru-RU')

    return matchesCategory && (!normalizedQuery || haystack.includes(normalizedQuery))
  })
}
